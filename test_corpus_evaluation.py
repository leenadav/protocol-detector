"""D09: the independent-corpus evaluation harness scores labelled flows and refuses unprovenanced input."""
import hashlib
import json
import os
import tempfile
import unittest

from protocol_adapters.make_sample_pcap import frame, pcap_bytes, udp_frame
from protocol_adapters.protocol_fixtures import DNS, client_hello_with
from tools import evaluate_corpus

HTTP_CLIENT, HTTP_SERVER = ("192.0.2.10", 52000), ("198.51.100.20", 80)
TLS_CLIENT, TLS_SERVER = ("192.0.2.11", 52001), ("198.51.100.21", 443)
DNS_CLIENT, DNS_SERVER = ("192.0.2.12", 53001), ("198.51.100.53", 53)
EXTRA_CLIENT, EXTRA_SERVER = ("192.0.2.13", 52002), ("198.51.100.22", 8080)
REQUEST = b"GET / HTTP/1.1\r\nHost: a.example\r\n\r\n"


def tcp_flow(client, server, payload):
    return [frame(client, server, 999, 0, 2), frame(server, client, 8999, 1000, 18), frame(client, server, 1000, 9000, 16),
            frame(client, server, 1000, 9000, 24, payload), frame(client, server, 1000 + len(payload), 9000, 17)]


def capture():
    frames = tcp_flow(HTTP_CLIENT, HTTP_SERVER, REQUEST) + tcp_flow(TLS_CLIENT, TLS_SERVER, client_hello_with([]))
    frames += [udp_frame(DNS_CLIENT, DNS_SERVER, DNS)] + tcp_flow(EXTRA_CLIENT, EXTRA_SERVER, REQUEST)
    return pcap_bytes(frames)


def manifest(sha, flows, **extra):
    document = {"corpus": "synthetic-selfcheck", "version": "1", "independent": False,
                "source": "generated by test_corpus_evaluation.py from repository fixtures; no captured traffic",
                "labelled_by": "the generating test (not independent of the engine's authors)",
                "label_basis": "generating client", "captures": [{"file": "c.pcap", "sha256": sha, "flows": flows}]}
    document.update(extra)
    return document


def flow(transport, client, server, family, application=None):
    item = {"transport": transport, "client": list(client), "server": list(server), "family": family}
    if application:
        item["application"] = application
    return item


class CorpusTests(unittest.TestCase):
    def setUp(self):
        self.folder = tempfile.mkdtemp()
        self.addCleanup(lambda: __import__("shutil").rmtree(self.folder, ignore_errors=True))
        data = capture()
        with open(os.path.join(self.folder, "c.pcap"), "wb") as handle:
            handle.write(data)
        self.sha = hashlib.sha256(data).hexdigest()

    def write(self, document):
        with open(os.path.join(self.folder, "manifest.json"), "w", encoding="utf-8") as handle:
            json.dump(document, handle)

    def test_scores_every_outcome_class(self):
        flows = [flow("tcp", HTTP_CLIENT, HTTP_SERVER, "http", "web-browsing"),        # correct
                 flow("tcp", TLS_CLIENT, TLS_SERVER, "http"),                           # wrong family (it is TLS)
                 flow("udp", DNS_CLIENT, DNS_SERVER, "dns", "dns"),                      # correct, application too
                 flow("tcp", ("192.0.2.99", 1), ("198.51.100.99", 2), "smb2")]          # missing: never in the capture
        self.write(manifest(self.sha, flows))
        report = evaluate_corpus.evaluate(self.folder)
        totals = report["totals"]
        self.assertEqual((totals["labelled_flows"], totals["correct"], totals["wrong"], totals["missing"], totals["unidentified"]), (4, 2, 1, 1, 0))
        self.assertEqual(totals["unlabelled_flows"], 1)                                 # the extra HTTP flow is reported, not scored
        self.assertEqual(totals["family_accuracy"], 0.5)
        self.assertEqual(report["confusion"], [{"expected": "http", "found": "tls", "count": 1}])
        families = report["families"]
        self.assertEqual((families["http"]["labelled"], families["http"]["correct"], families["http"]["wrong"]), (2, 1, 1))
        self.assertEqual((families["tls"]["labelled"], families["tls"]["false_positive"], families["tls"]["precision"]), (0, 1, 0.0))
        self.assertEqual((families["dns"]["recall"], families["dns"]["precision"]), (1.0, 1.0))
        self.assertEqual(families["smb2"]["missing"], 1)
        self.assertEqual(report["captures"][0]["input_quality"], {})
        self.assertTrue(report["engine"]["content"][0].startswith("2026."))
        text = evaluate_corpus.render(report)
        self.assertIn("NOT STATED", text)                                               # independent=false is said out loud
        self.assertIn("http → tls ×1", text)
        self.assertNotIn("a.example", json.dumps(report))                              # no payload or hostname leaves the harness

    def test_wrong_application_is_separate_from_wrong_family(self):
        self.write(manifest(self.sha, [flow("tcp", HTTP_CLIENT, HTTP_SERVER, "http", "webdav")]))
        totals = evaluate_corpus.evaluate(self.folder)["totals"]
        self.assertEqual((totals["correct"], totals["wrong_application"], totals["wrong"], totals["family_accuracy"]), (0, 1, 0, 1.0))

    def test_provenance_and_digest_are_required(self):
        document = manifest(self.sha, [flow("tcp", HTTP_CLIENT, HTTP_SERVER, "http")])
        del document["labelled_by"]
        self.write(document)
        with self.assertRaisesRegex(evaluate_corpus.CorpusError, "labelled_by"):
            evaluate_corpus.load_manifest(self.folder)
        self.write(manifest("0" * 64, [flow("tcp", HTTP_CLIENT, HTTP_SERVER, "http")]))
        with self.assertRaisesRegex(evaluate_corpus.CorpusError, "sha256 mismatch"):
            evaluate_corpus.load_manifest(self.folder)
        self.write(manifest(self.sha, [flow("tcp", HTTP_CLIENT, HTTP_SERVER, "not-a-family")]))
        with self.assertRaisesRegex(evaluate_corpus.CorpusError, "does not declare"):
            evaluate_corpus.load_manifest(self.folder)
        document = manifest(self.sha, [flow("tcp", HTTP_CLIENT, HTTP_SERVER, "http")])
        document["captures"][0]["file"] = "../c.pcap"
        self.write(document)
        with self.assertRaisesRegex(evaluate_corpus.CorpusError, "outside"):
            evaluate_corpus.load_manifest(self.folder)
        document = manifest(self.sha, [flow("tcp", HTTP_CLIENT, HTTP_SERVER, "http")])
        document["captures"][0]["options"] = {"payload_dump": True}
        self.write(document)
        with self.assertRaisesRegex(evaluate_corpus.CorpusError, "unsupported capture options"):
            evaluate_corpus.load_manifest(self.folder)

    def test_command_line_thresholds(self):
        self.write(manifest(self.sha, [flow("tcp", HTTP_CLIENT, HTTP_SERVER, "http"), flow("tcp", TLS_CLIENT, TLS_SERVER, "http")]))
        out_md, out_json = os.path.join(self.folder, "r.md"), os.path.join(self.folder, "r.json")
        self.assertEqual(evaluate_corpus.main([self.folder, "--write", out_md, "--json", out_json]), 0)
        self.assertEqual(evaluate_corpus.main([self.folder, "--max-wrong", "0"]), 1)
        self.assertEqual(evaluate_corpus.main([self.folder, "--min-accuracy", "0.9"]), 1)
        self.assertEqual(evaluate_corpus.main([self.folder, "--min-accuracy", "0.5"]), 0)
        with open(out_json, encoding="utf-8") as handle:
            self.assertEqual(json.load(handle)["totals"]["wrong"], 1)
        os.remove(os.path.join(self.folder, "manifest.json"))
        self.assertEqual(evaluate_corpus.main([self.folder]), 2)

    def test_capture_options_reach_the_analyzer(self):
        # Client-side-only capture: default mode cannot identify it; the asymmetric option can.
        frames = [frame(HTTP_CLIENT, HTTP_SERVER, 999, 0, 2), frame(HTTP_CLIENT, HTTP_SERVER, 1000, 5000, 24, REQUEST),
                  frame(HTTP_CLIENT, HTTP_SERVER, 1000 + len(REQUEST), 5000, 17)]
        data = pcap_bytes(frames)
        with open(os.path.join(self.folder, "c.pcap"), "wb") as handle:
            handle.write(data)
        sha = hashlib.sha256(data).hexdigest()
        labels = [flow("tcp", HTTP_CLIENT, HTTP_SERVER, "http")]
        self.write(manifest(sha, labels))
        self.assertEqual(evaluate_corpus.evaluate(self.folder)["totals"]["unidentified"], 1)
        document = manifest(sha, labels)
        document["captures"][0]["options"] = {"observation": "asymmetric"}
        self.write(document)
        self.assertEqual(evaluate_corpus.evaluate(self.folder)["totals"]["correct"], 1)


if __name__ == "__main__":
    unittest.main()
